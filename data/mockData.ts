import { addDays, differenceInCalendarDays, format, parseISO } from 'date-fns';

// Sample data was written as if today were 5 June 2026. Every date below is
// shifted by the same number of days so the demo always looks current.
const SAMPLE_TODAY = parseISO('2026-06-05');
const OFFSET = differenceInCalendarDays(new Date(), SAMPLE_TODAY);
function s(date: string): string {
  const shifted = addDays(parseISO(date), OFFSET);
  return date.includes('T') ? shifted.toISOString() : format(shifted, 'yyyy-MM-dd');
}

